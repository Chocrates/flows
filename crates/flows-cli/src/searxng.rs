//! Optional self-hosted SearXNG for the `searxng` web_search backend. Detects any
//! available container engine (docker / podman / nerdctl / finch / …) and runs the
//! official image with the JSON API enabled, so flows can query it.

use std::path::PathBuf;
use std::process::{Command, Stdio};

/// Container engines we know how to drive, in preference order. They share the
/// same `run`/`rm`/`ps` surface, so one code path works for all.
const ENGINES: &[&str] = &["docker", "podman", "nerdctl", "finch"];

const CONTAINER: &str = "flows-searxng";
// Fully-qualified so podman (which disables short-name resolution) works too;
// docker / nerdctl / finch all accept the docker.io/ prefix as well.
const IMAGE: &str = "docker.io/searxng/searxng:latest";
const HOST_PORT: u16 = 8888;

/// Pick an engine whose daemon/context is actually usable. Falls back to naming
/// what's installed-but-not-running so the error is actionable.
fn detect_engine() -> Result<String, String> {
    let quiet = || (Stdio::null(), Stdio::null());
    let mut installed = Vec::new();
    for e in ENGINES {
        let (o, r) = quiet();
        let present = Command::new(e)
            .arg("--version")
            .stdout(o)
            .stderr(r)
            .status()
            .map(|s| s.success())
            .unwrap_or(false);
        if !present {
            continue;
        }
        installed.push(*e);
        let (o, r) = quiet();
        let usable = Command::new(e)
            .arg("info")
            .stdout(o)
            .stderr(r)
            .status()
            .map(|s| s.success())
            .unwrap_or(false);
        if usable {
            return Ok((*e).to_string());
        }
    }
    if installed.is_empty() {
        Err(format!(
            "no container engine found — install one of: {}",
            ENGINES.join(", ")
        ))
    } else {
        Err(format!(
            "found {} but none have a running daemon/context — start it first",
            installed.join(", ")
        ))
    }
}

fn settings_dir() -> PathBuf {
    crate::flows_dir().join("searxng")
}

/// Write a minimal SearXNG settings.yml that (1) enables the JSON output format
/// flows needs and (2) disables the bot limiter so scripted queries aren't
/// blocked. Idempotent — only written if missing, so users can hand-edit it.
fn ensure_settings() -> Result<PathBuf, String> {
    let dir = settings_dir();
    std::fs::create_dir_all(&dir).map_err(|e| e.to_string())?;
    let file = dir.join("settings.yml");
    if !file.exists() {
        // A random secret so the instance isn't using a well-known key.
        let secret = format!("{:x}{:x}", rand_u64(), rand_u64());
        let yaml = format!(
            "# Generated by `flows searxng`. Hand-edit as you like — it won't be overwritten.\n\
             use_default_settings: true\n\
             server:\n  secret_key: \"{secret}\"\n  limiter: false\n  image_proxy: true\n\
             search:\n  formats:\n    - html\n    - json\n"
        );
        std::fs::write(&file, yaml).map_err(|e| e.to_string())?;
    }
    Ok(dir)
}

/// Cheap random (no rand crate): mix time + address entropy.
fn rand_u64() -> u64 {
    use std::time::{SystemTime, UNIX_EPOCH};
    let t = SystemTime::now()
        .duration_since(UNIX_EPOCH)
        .map(|d| d.as_nanos() as u64)
        .unwrap_or(0);
    let a = &t as *const u64 as u64;
    t ^ a.rotate_left(17)
}

fn running(engine: &str) -> bool {
    Command::new(engine)
        .args(["ps", "--filter", &format!("name={CONTAINER}"), "-q"])
        .output()
        .map(|o| !o.stdout.is_empty())
        .unwrap_or(false)
}

pub fn cmd(action: &str) -> Result<(), String> {
    match action {
        "up" | "start" => up(),
        "down" | "stop" => down(),
        "status" => status(),
        other => Err(format!(
            "unknown action {other:?} — use: up | down | status"
        )),
    }
}

fn up() -> Result<(), String> {
    let engine = detect_engine()?;
    let dir = ensure_settings()?;
    if running(&engine) {
        println!("SearXNG already running ({engine}) at http://localhost:{HOST_PORT}");
        return print_config_hint();
    }
    // Remove any stopped leftover with the same name, then run detached.
    let _ = Command::new(&engine)
        .args(["rm", "-f", CONTAINER])
        .stdout(Stdio::null())
        .stderr(Stdio::null())
        .status();
    println!("starting SearXNG via {engine} (image {IMAGE})…");
    let status = Command::new(&engine)
        .args([
            "run",
            "-d",
            "--name",
            CONTAINER,
            "--restart",
            "unless-stopped", // survive reboots / daemon restarts
            "-p",
            &format!("{HOST_PORT}:8080"),
            "-v",
            &format!("{}:/etc/searxng", dir.display()),
            IMAGE,
        ])
        .status()
        .map_err(|e| format!("{engine} run failed: {e}"))?;
    if !status.success() {
        return Err(format!("{engine} run exited {status}"));
    }
    println!("SearXNG up at http://localhost:{HOST_PORT}  (first start pulls the image + warms up)");
    print_config_hint()
}

fn down() -> Result<(), String> {
    let engine = detect_engine()?;
    let status = Command::new(&engine)
        .args(["rm", "-f", CONTAINER])
        .status()
        .map_err(|e| format!("{engine} rm failed: {e}"))?;
    if status.success() {
        println!("SearXNG stopped + removed");
        Ok(())
    } else {
        Err(format!("{engine} rm exited {status}"))
    }
}

fn status() -> Result<(), String> {
    let engine = detect_engine()?;
    println!("engine: {engine}");
    if running(&engine) {
        println!("SearXNG: running at http://localhost:{HOST_PORT}");
    } else {
        println!("SearXNG: not running — start with `flows searxng up`");
    }
    Ok(())
}

fn print_config_hint() -> Result<(), String> {
    println!("\nEnable it in ~/.flows/config.yml:");
    println!("  tools:");
    println!("    web_search:");
    println!("      backend: searxng");
    println!("      base_url: http://localhost:{HOST_PORT}");
    Ok(())
}
